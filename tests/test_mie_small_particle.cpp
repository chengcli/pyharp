template <typename T>
static void check_cases(double tol) {
  constexpr int max_order = 64;
  harp::Complex<T> work[3 * max_order];
  for (auto const& c : kCases) {
    auto out = harp::mie_efficiency_device<T>(T(c.n), T(c.k), T(c.x), work, max_order);
    ASSERT_EQ(out.status, 0) << "m = " << c.n << " - " << c.k << "i, x = " << c.x;
    double qext = out.qext, qsca = out.qsca;
    EXPECT_NEAR(qext, c.qext, tol * c.qext)
        << "Q_ext, m = " << c.n << " - " << c.k << "i, x = " << c.x;
    double ssa = qsca / qext, ssa_ref = c.qsca / c.qext;
    EXPECT_NEAR(ssa, ssa_ref, tol * ssa_ref)
        << "SSA, m = " << c.n << " - " << c.k << "i, x = " << c.x;
  }
}

TEST(MieSmallParticle, double_precision) { check_cases<double>(1e-6); }

TEST(MieSmallParticle, single_precision) { check_cases<float>(1e-4); }

